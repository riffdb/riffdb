fn emit_go_reactive_parameters(
    output: &mut String,
    name: &str,
    parameters: &[riffdb_query_ir::ReactiveParameterV1],
    contract: &ContractBundle,
) {
    writeln!(output, "type {name}Params struct {{").unwrap();
    for parameter in parameters {
        writeln!(
            output,
            "\t{} {}",
            go_public(parameter.name()),
            go_reactive_type(parameter.type_name(), contract)
        )
        .unwrap();
    }
    writeln!(
        output,
        "}}\nfunc encode{name}Params(parameters {name}Params) map[string]riffdb.Value {{ return map[string]riffdb.Value{{"
    )
    .unwrap();
    for parameter in parameters {
        writeln!(
            output,
            "\t{:?}: {},",
            parameter.name(),
            go_reactive_encode_expr(
                &format!("parameters.{}", go_public(parameter.name())),
                parameter.type_name(),
                contract,
            )
        )
        .unwrap();
    }
    output.push_str("} }\n");
}

fn emit_go_reactive_operation_vars(
    output: &mut String,
    source_name: &str,
    operations: &BTreeMap<(String, String), (String, String)>,
) {
    let name = go_public(source_name);
    for ((operation, action), (driver_name, schema_hash)) in operations {
        if operation != source_name || action.starts_with("react_") {
            continue;
        }
        writeln!(
            output,
            "var {name}{}Operation = riffdb.Operation{{Name: {driver_name:?}, InputSchemaHash: {schema_hash:?}}}",
            go_public(action)
        )
        .unwrap();
    }
}

