/// Generates one dependency-light Go package for all named queries and commands.
#[must_use]
pub fn generate_go_client(module: &QueryModule, contract: &ContractBundle) -> String {
    generate_go_client_inner(module, contract, &[])
}

/// Generates one dependency-light Go package including exact reactive facades.
#[must_use]
pub fn generate_go_application_client(
    module: &QueryModule,
    contract: &ContractBundle,
    reactive_modules: &[ReactiveModulePlanV1],
) -> String {
    generate_go_client_inner(module, contract, reactive_modules)
}

fn generate_go_client_inner(
    module: &QueryModule,
    contract: &ContractBundle,
    reactive_modules: &[ReactiveModulePlanV1],
) -> String {
    let query_operations = generate_mcp_tools(module)
        .expect("validated query operations")
        .into_iter()
        .map(|operation| {
            (
                operation.operation_name,
                (operation.name, schema_hash(&operation.input_schema)),
            )
        })
        .collect::<BTreeMap<_, _>>();
    let command_operations = generate_mcp_commands(module, contract)
        .expect("validated command operations")
        .into_iter()
        .map(|operation| {
            (
                operation.operation_name,
                (operation.name, schema_hash(&operation.input_schema)),
            )
        })
        .collect::<BTreeMap<_, _>>();
    let mut output = String::new();
    writeln!(
        output,
        "// Code generated by riffdb-query-module. DO NOT EDIT."
    )
    .unwrap();
    writeln!(output, "package {}\n", go_package(module.name().as_str())).unwrap();
    if reactive_modules.is_empty() {
        output.push_str(
            "import (\n\t\"context\"\n\t\"errors\"\n\n\triffdb \"riffdb.dev/application\"\n)\n\n",
        );
    } else {
        output.push_str(
            "import (\n\t\"context\"\n\t\"errors\"\n\t\"time\"\n\n\triffdb \"riffdb.dev/application\"\n)\n\n",
        );
    }
    writeln!(
        output,
        "const QueryModuleHash = \"{}\"",
        hex(module.identity().as_bytes())
    )
    .unwrap();
    writeln!(
        output,
        "const ContractLineage = \"{}\"",
        module.contract_lineage().as_str()
    )
    .unwrap();
    writeln!(
        output,
        "const ContractVersion uint64 = {}",
        module.contract_version().get()
    )
    .unwrap();
    writeln!(
        output,
        "const ContractBundleHash = \"{}\"\n",
        hex(module.contract_hash().as_bytes())
    )
    .unwrap();
    output.push_str("type QueryOptions = riffdb.Options\ntype QueryResult[T any] struct { Value T; ApplicationHead uint64; NextCursor string }\ntype CommandResult[T any] struct { Outcome T; CommitSequence *uint64; Replayed bool; OutcomeURI string }\ntype BatchItem[T any] struct { Index uint32; Result *CommandResult[T]; Error error }\ntype BatchResult[T any] struct { Items []BatchItem[T]; Checkpoint uint32; Total uint32 }\n\n");
    if !reactive_modules.is_empty() {
        output.push_str("type ConsumerOptions struct { BatchLimit uint32; InFlightLimit uint32; LeaseSeconds uint64; MaximumWait time.Duration }\nfunc DefaultConsumerOptions() ConsumerOptions { return ConsumerOptions{BatchLimit: 1, InFlightLimit: 16, LeaseSeconds: 60, MaximumWait: 30 * time.Second} }\nfunc (options ConsumerOptions) validate() error { if options.BatchLimit < 1 || options.BatchLimit > 64 || options.InFlightLimit < 1 || options.InFlightLimit > 64 || options.LeaseSeconds < 5 || options.LeaseSeconds > 900 || options.MaximumWait < 0 || options.MaximumWait > 30*time.Second { return errors.New(\"invalid generated RiffDB consumer options\") }; return nil }\nfunc retryDelayNanos(delay time.Duration) (uint64, error) { if delay < 0 || delay > 5*time.Minute { return 0, errors.New(\"invalid generated RiffDB retry delay\") }; return uint64(delay), nil }\n\n");
    }
    emit_enums(&mut output, contract);
    emit_entities(&mut output, contract);
    emit_query_types(&mut output, module, contract);
    emit_command_types(&mut output, contract);
    output.push_str("type Client struct { session *riffdb.Session; commandAttempts uint32 }\n\nfunc NewClient(session *riffdb.Session, commandAttempts uint32) (*Client, error) { if session == nil || commandAttempts < 1 || commandAttempts > 10 { return nil, errors.New(\"invalid generated RiffDB client configuration\") }; return &Client{session: session, commandAttempts: commandAttempts}, nil }\n\n");
    emit_entity_codecs(&mut output, contract);
    emit_query_methods(&mut output, module, contract, &query_operations);
    emit_command_methods(&mut output, contract, &command_operations);
    emit_reactive_modules(&mut output, contract, reactive_modules);
    output.push_str("func requiredField(fields map[string]riffdb.Value, name string) (riffdb.Value, error) { value, ok := fields[name]; if !ok { return riffdb.Value{}, errors.New(\"RiffDB driver result is missing a generated field\") }; return value, nil }\n");
    output
}

fn emit_enums(output: &mut String, contract: &ContractBundle) {
    for enumeration in contract.schema().enums() {
        let name = go_public(enumeration.name());
        writeln!(output, "type {name} string\n\nconst (").unwrap();
        for variant in enumeration.variants() {
            writeln!(
                output,
                "\t{name}{} {name} = \"{}\"",
                go_public(variant.name()),
                variant.name()
            )
            .unwrap();
        }
        output.push_str(")\n\n");
    }
}

fn emit_entities(output: &mut String, contract: &ContractBundle) {
    for entity in contract.schema().entities() {
        writeln!(output, "type {} struct {{", go_public(entity.name())).unwrap();
        for field in entity.record().fields() {
            writeln!(
                output,
                "\t{} {}",
                go_public(field.name()),
                go_type(field.value_type(), contract)
            )
            .unwrap();
        }
        output.push_str("}\n\n");
    }
}

fn emit_query_types(output: &mut String, module: &QueryModule, contract: &ContractBundle) {
    for query in module.queries() {
        let name = go_public(query.name());
        writeln!(output, "type {name}Params struct {{").unwrap();
        for parameter in query.plan().schemas().parameters() {
            let mut ty = go_named_type(parameter.value_type(), contract);
            if (parameter.has_default()
                || matches!(
                    parameter.value_type(),
                    NamedTypeSchema::Cursor | NamedTypeSchema::Optional(_)
                ))
                && !ty.starts_with('*')
            {
                ty = format!("*{ty}");
            }
            writeln!(output, "\t{} {}", go_public(parameter.name()), ty).unwrap();
        }
        output.push_str("}\n\n");
        writeln!(output, "type {name}Result interface {{ is{name}Result() }}").unwrap();
        for branch in query.plan().schemas().results() {
            let branch_name = format!("{name}{}", go_public(branch.name()));
            writeln!(output, "type {branch_name} struct {{\n\tOutcome string").unwrap();
            for field in branch.fields() {
                writeln!(
                    output,
                    "\t{} {}",
                    go_public(field.name()),
                    go_named_type(field.value_type(), contract)
                )
                .unwrap();
            }
            writeln!(output, "}}\nfunc ({branch_name}) is{name}Result() {{}}\n").unwrap();
        }
    }
}

fn emit_command_types(output: &mut String, contract: &ContractBundle) {
    let mut commands = contract.commands().iter().collect::<Vec<_>>();
    commands.sort_by(|left, right| left.name().cmp(right.name()));
    for command in commands {
        let name = go_public(command.name());
        writeln!(output, "type {name}Input struct {{").unwrap();
        for field in command.input().record().fields() {
            writeln!(
                output,
                "\t{} {}",
                go_public(field.name()),
                go_type(field.value_type(), contract)
            )
            .unwrap();
        }
        writeln!(
            output,
            "}}\ntype {name}Outcome interface {{ is{name}Outcome() }}"
        )
        .unwrap();
        for outcome in command.outcomes() {
            let outcome_name = format!("{name}{}", go_public(outcome.name()));
            writeln!(output, "type {outcome_name} struct {{\n\tOutcome string").unwrap();
            for field in outcome.payload().fields() {
                writeln!(
                    output,
                    "\t{} {}",
                    go_public(field.name()),
                    go_type(field.value_type(), contract)
                )
                .unwrap();
            }
            writeln!(output, "}}\nfunc ({outcome_name}) is{name}Outcome() {{}}\n").unwrap();
        }
    }
}

fn emit_entity_codecs(output: &mut String, contract: &ContractBundle) {
    for entity in contract.schema().entities() {
        let name = go_public(entity.name());
        writeln!(output, "func encode{name}(value {name}) riffdb.Value {{ return riffdb.Record(map[string]riffdb.Value{{").unwrap();
        for field in entity.record().fields() {
            writeln!(
                output,
                "\t\"{}\": {},",
                field.name(),
                encode_expr(
                    &format!("value.{}", go_public(field.name())),
                    field.value_type(),
                    contract
                )
            )
            .unwrap();
        }
        output.push_str("}) }\n");
        writeln!(output, "func decode{name}(value riffdb.Value) ({name}, error) {{ fields, err := riffdb.RecordFields(value); if err != nil {{ return {name}{{}}, err }}; var result {name}; var raw riffdb.Value").unwrap();
        for field in entity.record().fields() {
            let public = go_public(field.name());
            writeln!(output, "raw, err = requiredField(fields, \"{}\"); if err != nil {{ return result, err }}; result.{public}, err = {}; if err != nil {{ return result, err }}", field.name(), decode_expr("raw", field.value_type(), contract)).unwrap();
        }
        output.push_str("return result, nil }\n\n");
    }
}

fn emit_query_methods(
    output: &mut String,
    module: &QueryModule,
    contract: &ContractBundle,
    operations: &BTreeMap<String, (String, String)>,
) {
    for query in module.queries() {
        let source_name = query.name();
        let name = go_public(source_name);
        let (operation, schema_hash) = &operations[source_name];
        writeln!(output, "var {name}Operation = riffdb.Operation{{Name: \"{operation}\", InputSchemaHash: \"{schema_hash}\"}}").unwrap();
        writeln!(output, "func decode{name}Result(value riffdb.Value) ({name}Result, error) {{ fields, err := riffdb.RecordFields(value); if err != nil {{ return nil, err }}; outcomeValue, err := requiredField(fields, \"outcome\"); if err != nil {{ return nil, err }}; outcome, err := riffdb.EnumValue(outcomeValue); if err != nil {{ return nil, err }}; var raw riffdb.Value; switch outcome {{").unwrap();
        for branch in query.plan().schemas().results() {
            let branch_name = format!("{name}{}", go_public(branch.name()));
            writeln!(
                output,
                "case \"{}\": result := {branch_name}{{Outcome: outcome}}",
                branch.name()
            )
            .unwrap();
            for field in branch.fields() {
                let public = go_public(field.name());
                writeln!(output, "raw, err = requiredField(fields, \"{}\"); if err != nil {{ return nil, err }}; result.{public}, err = {}; if err != nil {{ return nil, err }}", field.name(), decode_named_expr("raw", field.value_type(), contract)).unwrap();
            }
            output.push_str("return result, nil\n");
        }
        output.push_str("default: return nil, errors.New(\"RiffDB driver returned unknown query outcome\") } }\n");
        writeln!(output, "func (client *Client) {name}(ctx context.Context, parameters {name}Params, options QueryOptions) (QueryResult[{name}Result], error) {{ input := map[string]riffdb.Value{{}}").unwrap();
        for parameter in query.plan().schemas().parameters() {
            let field = go_public(parameter.name());
            if parameter.has_default()
                || matches!(
                    parameter.value_type(),
                    NamedTypeSchema::Cursor | NamedTypeSchema::Optional(_)
                )
            {
                let inner = if go_named_type(parameter.value_type(), contract).starts_with('*') {
                    format!("parameters.{field}")
                } else {
                    format!("*parameters.{field}")
                };
                writeln!(
                    output,
                    "if parameters.{field} != nil {{ input[\"{}\"] = {} }}",
                    parameter.name(),
                    encode_named_expr(&inner, parameter.value_type(), contract)
                )
                .unwrap();
            } else {
                writeln!(
                    output,
                    "input[\"{}\"] = {}",
                    parameter.name(),
                    encode_named_expr(
                        &format!("parameters.{field}"),
                        parameter.value_type(),
                        contract
                    )
                )
                .unwrap();
            }
        }
        writeln!(output, "response, err := client.session.Invoke(ctx, {name}Operation, input, options); if err != nil {{ return QueryResult[{name}Result]{{}}, err }}; if response.ApplicationHead == nil {{ return QueryResult[{name}Result]{{}}, errors.New(\"RiffDB driver omitted query frontier\") }}; value, err := decode{name}Result(response.Value); if err != nil {{ return QueryResult[{name}Result]{{}}, err }}; return QueryResult[{name}Result]{{Value: value, ApplicationHead: *response.ApplicationHead, NextCursor: response.Cursor}}, nil }}\n").unwrap();
    }
}

fn emit_command_methods(
    output: &mut String,
    contract: &ContractBundle,
    operations: &BTreeMap<String, (String, String)>,
) {
    let mut commands = contract.commands().iter().collect::<Vec<_>>();
    commands.sort_by(|left, right| left.name().cmp(right.name()));
    for command in commands {
        let source_name = command.name();
        let name = go_public(source_name);
        let (operation, schema_hash) = &operations[source_name];
        writeln!(output, "var {name}Operation = riffdb.Operation{{Name: \"{operation}\", InputSchemaHash: \"{schema_hash}\"}}").unwrap();
        writeln!(output, "func encode{name}Input(input {name}Input) map[string]riffdb.Value {{ return map[string]riffdb.Value{{").unwrap();
        for field in command.input().record().fields() {
            writeln!(
                output,
                "\t\"{}\": {},",
                field.name(),
                encode_expr(
                    &format!("input.{}", go_public(field.name())),
                    field.value_type(),
                    contract
                )
            )
            .unwrap();
        }
        output.push_str("} }\n");
        writeln!(output, "func decode{name}Outcome(value riffdb.Value) ({name}Outcome, error) {{ fields, err := riffdb.RecordFields(value); if err != nil {{ return nil, err }}; outcomeValue, err := requiredField(fields, \"outcome\"); if err != nil {{ return nil, err }}; outcome, err := riffdb.EnumValue(outcomeValue); if err != nil {{ return nil, err }}; var raw riffdb.Value; switch outcome {{").unwrap();
        for outcome in command.outcomes() {
            let outcome_name = format!("{name}{}", go_public(outcome.name()));
            writeln!(
                output,
                "case \"{}\": result := {outcome_name}{{Outcome: outcome}}",
                outcome.name()
            )
            .unwrap();
            for field in outcome.payload().fields() {
                let public = go_public(field.name());
                writeln!(output, "raw, err = requiredField(fields, \"{}\"); if err != nil {{ return nil, err }}; result.{public}, err = {}; if err != nil {{ return nil, err }}", field.name(), decode_expr("raw", field.value_type(), contract)).unwrap();
            }
            output.push_str("return result, nil\n");
        }
        output.push_str("default: return nil, errors.New(\"RiffDB driver returned unknown command outcome\") } }\n");
        writeln!(output, "func (client *Client) {name}(ctx context.Context, input {name}Input) (CommandResult[{name}Outcome], error) {{ response, err := client.session.Invoke(ctx, {name}Operation, encode{name}Input(input), riffdb.Options{{MaximumAttempts: client.commandAttempts}}); if err != nil {{ return CommandResult[{name}Outcome]{{}}, err }}; outcome, err := decode{name}Outcome(response.Value); if err != nil {{ return CommandResult[{name}Outcome]{{}}, err }}; return CommandResult[{name}Outcome]{{Outcome: outcome, CommitSequence: response.ApplicationHead, Replayed: response.Replayed, OutcomeURI: response.Cursor}}, nil }}").unwrap();
        writeln!(output, "func (client *Client) {name}Batch(ctx context.Context, inputs []{name}Input, concurrency, checkpoint uint32) (BatchResult[{name}Outcome], error) {{ encoded := make([]map[string]riffdb.Value, len(inputs)); for index, input := range inputs {{ encoded[index] = encode{name}Input(input) }}; response, err := client.session.Batch(ctx, {name}Operation, encoded, concurrency, checkpoint, riffdb.Options{{MaximumAttempts: client.commandAttempts}}); if err != nil {{ return BatchResult[{name}Outcome]{{}}, err }}; result := BatchResult[{name}Outcome]{{Checkpoint: response.Checkpoint, Total: response.Total, Items: make([]BatchItem[{name}Outcome], 0, len(response.Items))}}; for _, item := range response.Items {{ converted := BatchItem[{name}Outcome]{{Index: item.Index}}; if item.Error != nil {{ converted.Error = item.Error }} else if item.Result != nil {{ outcome, decodeErr := decode{name}Outcome(item.Result.Value); if decodeErr != nil {{ return BatchResult[{name}Outcome]{{}}, decodeErr }}; converted.Result = &CommandResult[{name}Outcome]{{Outcome: outcome, CommitSequence: item.Result.CommitSequence, Replayed: item.Result.Replayed, OutcomeURI: item.Result.OutcomeURI}} }}; result.Items = append(result.Items, converted) }}; return result, nil }}\n").unwrap();
    }
}

